import type { FontAsset } from '@formancy/report-runtime'

/**
 * Fonts whose family, name ID 1, is as long as Word reads one, a character
 * longer, and as long as an attribute can write one (0068): the least
 * TrueType font report-spec's reader accepts, with the digits a page
 * field prints mapped beside its 'A' and 'B', made by report-spec's font
 * test support (`font-test-support.ts` there, 0040) on 18 November
 * 2026 as
 *
 *   font({
 *     name: name([windows(1, family), windows(2, 'Regular'), windows(6, postScriptName)]),
 *     cmap: cmap([[3, 1, format4([{ start: 0x30, end: 0x39, glyphs: new Array(10).fill(1) }, ...AB])]]),
 *   })
 *
 * and held here as its bytes, since that support is exported by nothing
 * and a package reads another through what it builds. `fonts.test.ts`
 * holds each to the family `readFont` reads of it.
 */

const asset = (id: string, base64: string): FontAsset => ({ id, digest: `sha256:${'0'.repeat(64)}`, bytes: new Uint8Array(Buffer.from(base64, 'base64')) })

