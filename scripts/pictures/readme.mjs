// README.md's pictures, written where they are generated, and the repository
// guard's checks of them. formancy.ai-data's scripts/pictures/readme.mjs (its
// 0038), with a line closing each app's region and no steps.
//
// Two jobs, both pure over what `repository()` reads, so readme.test.mjs runs
// them in `pnpm test:repo` without a browser:
//
// - **Render.** README.md carries one generated region per placement: `hero`
//   for the hero scene, the picture the README opens with, and one per app
//   for the rest, in scenes.json's order. A `hero` or `inline` scene is its
//   picture at its recorded CSS width and its italic caption; each run of
//   consecutive `more` scenes is one <details> whose summary is derived from
//   their titles. The hero's region ends with HERO_LINE, which sends the
//   reader to the app's; an app's ends with LINE, which says how the
//   pictures are taken and held. `node scripts/pictures/readme.mjs --write`
//   writes the regions; nothing else does.
// - **Check.** Each function below returns the sentences that are wrong with
//   the repository, empty when nothing is: the regions are the render, every
//   scene has its picture and the bytes match, nothing else is in the
//   pictures' directory, every caption quotes only what its parts say, one
//   look, every link and picture the regions show resolves, the scenes'
//   shape, and a guard on the guard.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { marker } from '../generated-block.mjs'
import { describeLook, digest, IMAGES, misquotes, pictureOf, readRecord, readScenes, REPO, serialize, undecodable } from './record.mjs'

export const README = join(REPO, 'README.md')

const PLACEMENTS = ['hero', 'inline', 'more']
// The one grammar of a generated region (scripts/generated-block.mjs), which
// names a single source: scenes.json, where each caption and alt comes from.
// captured.json is what the pictures were held to, and readme.test.mjs
// checks it beside them.
export const START = (name) => marker('scripts/pictures/readme.mjs', { from: 'scripts/pictures/scenes.json', name })
export const END = '<!-- end generated -->'
/** Any of this file's markers, whatever region it names. */
const ANY_START = /<!-- generated by scripts\/pictures\/readme\.mjs from [^>]*: ([^;>]*); do not edit -->/g

/** The sentence every region ends with: how its pictures are taken, what holds them, and what does not. */
export const LINE =
  "Every picture in this section is taken by `node scripts/pictures.mjs`, in Chromium, from the built Studio driven through its controls, never by hand. `pnpm --filter @formancy/report-studio test:pictures` walks the same states and fails when a picture's elements no longer say what they said when it was taken, or when a caption quotes what they do not say, and `pnpm test:repo` holds every caption to its picture's record. CI runs both, in its `browser` job. Neither looks at the pixels: a change of colour or layout alone is seen only by looking. And a caption is held to the text its elements hold, not to how much of that text a pane has scrolled or cut out of the picture."

/** The sentence the hero's region ends with: where the rest are, and how they are held. */
export const HERO_LINE = 'Taken by a script from the built Studio and held to the text it shows, as every picture under [The Studio](#the-studio) is.'

/** The region a scene is drawn in: the hero's own, or its app's. */
const regionOf = (scene) => (scene.placement === 'hero' ? 'hero' : scene.app)

/** The regions README.md must carry, in scenes.json's order: derived, so an app given scenes is given a region. */
export const regionNames = (scenes) => [...new Set(scenes.map(regionOf))]

const attribute = (text) => text.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')

/** One scene as README.md shows it: the picture at its recorded CSS width, then its caption. */
function picture(scene, record) {
  const entry = record[scene.id]
  if (entry === undefined)
    throw new Error(`${scene.id} has no record in docs/images/readme/captured.json: \`node scripts/pictures.mjs --scene ${scene.id}\` takes it`)
  return [`<img src="./${pictureOf(scene.id)}" width="${String(entry.css.width)}" alt="${attribute(scene.alt)}">`, '', `*${scene.caption}*`].join('\n')
}

/** Every generated region's text, by name, from scenes.json and the record. */
export function render(scenes, record) {
  const rendered = {}
  for (const name of regionNames(scenes)) {
    const blocks = []
    let more = []
    const close = () => {
      if (more.length === 0) return
      blocks.push(
        [
          '<details>',
          `<summary>More: ${more.map((scene) => scene.title).join(', ')}</summary>`,
          '',
          ...more
            .map((scene) => picture(scene, record))
            .join('\n\n')
            .split('\n'),
          '',
          '</details>',
        ].join('\n'),
      )
      more = []
    }
    for (const scene of scenes.filter((candidate) => regionOf(candidate) === name)) {
      if (scene.placement === 'more') {
        more.push(scene)
        continue
      }
      close()
      blocks.push(picture(scene, record))
    }
    close()
    blocks.push(name === 'hero' ? HERO_LINE : LINE)
    rendered[name] = blocks.join('\n\n')
  }
  return rendered
}

/** The generated regions of `markdown`, by name; throws when one is repeated or unclosed. */
export function generatedRegions(markdown) {
  const text = markdown.replaceAll('\r\n', '\n')
  const found = {}
  for (const match of text.matchAll(ANY_START)) {
    const [opening, name] = match
    if (Object.hasOwn(found, name)) throw new Error(`README.md holds the pictures region "${name}" twice`)
    const from = match.index + opening.length
    const end = text.indexOf(END, from)
    const next = text.slice(from).search(ANY_START)
    if (end === -1 || (next !== -1 && from + next < end)) throw new Error(`README.md: the pictures region "${name}" is never closed by ${END}`)
    found[name] = text.slice(from, end).trim()
  }
  return found
}

/** `markdown` with every generated region replaced by what `render` gives; throws when a region is missing or one is not this render's. */
export function rewrite(markdown, scenes, record) {
  let text = markdown.replaceAll('\r\n', '\n')
  const present = Object.keys(generatedRegions(text))
  const names = regionNames(scenes)
  const missing = names.filter((name) => !present.includes(name))
  const stray = present.filter((name) => !names.includes(name))
  if (missing.length > 0 || stray.length > 0) {
    throw new Error(
      `README.md must hold the pictures regions ${names.join(', ')}, each opened by ${START('<name>')}${missing.length > 0 ? `; ${missing.join(', ')} missing` : ''}${stray.length > 0 ? `; ${stray.join(', ')} no scene's` : ''}`,
    )
  }
  const rendered = render(scenes, record)
  for (const name of names) {
    const start = text.indexOf(START(name)) + START(name).length
    const end = text.indexOf(END, start)
    // Blank lines around, so Markdown reads the HTML and the captions as blocks of their own.
    text = `${text.slice(0, start)}\n\n${rendered[name]}\n\n${text.slice(end)}`
  }
  return text
}

/** What the checks read, from the working tree. */
export function repository() {
  const scenes = readScenes()
  const recordText = existsSync(join(IMAGES, 'captured.json')) ? readFileSync(join(IMAGES, 'captured.json'), 'utf8') : undefined
  return {
    scenes,
    record: recordText === undefined ? {} : JSON.parse(recordText),
    recordText,
    readme: readFileSync(README, 'utf8'),
    listing: existsSync(IMAGES) ? readdirSync(IMAGES) : [],
    file: (path) => (existsSync(join(REPO, path)) ? readFileSync(join(REPO, path)) : undefined),
    exists: (path) => existsSync(join(REPO, path)),
    appScripts: readdirSync(join(REPO, 'apps')).filter((app) => existsSync(join(REPO, 'apps', app, 'scripts', 'pictures.mjs'))),
  }
}

/** The regions equal the render; each region appears once and no other pictures region exists. */
export function regionProblems({ scenes, record, readme }) {
  let present
  try {
    present = generatedRegions(readme)
  } catch (error) {
    return [error.message]
  }
  const names = regionNames(scenes)
  const problems = []
  for (const name of Object.keys(present)) if (!names.includes(name)) problems.push(`README.md holds a pictures region "${name}" no scene is drawn in`)
  for (const name of names) if (!Object.hasOwn(present, name)) problems.push(`README.md does not hold the pictures region "${name}", opened by ${START(name)}`)
  let rendered
  try {
    rendered = render(scenes, record)
  } catch (error) {
    return [...problems, error.message]
  }
  for (const name of names) {
    if (Object.hasOwn(present, name) && present[name] !== rendered[name])
      problems.push(`README.md's pictures region "${name}" is not what scenes.json and captured.json render: run \`node scripts/pictures/readme.mjs --write\``)
  }
  return problems
}

/** Every scene has a record, and a picture whose bytes and sha256 are the record's; captured.json is as the camera writes it. */
export function integrityProblems({ scenes, record, recordText, file }) {
  if (recordText === undefined) return ['docs/images/readme/captured.json does not exist: `node scripts/pictures.mjs --all` takes the pictures and writes it']
  const problems = []
  if (recordText !== serialize(record, scenes))
    problems.push('docs/images/readme/captured.json is not as the camera writes it: pretty-printed, keyed in scenes.json order, LF only')
  for (const scene of scenes) {
    const entry = record[scene.id]
    if (entry === undefined) {
      problems.push(`${scene.id} has no record: \`node scripts/pictures.mjs --scene ${scene.id}\` takes it`)
      continue
    }
    if (entry.file !== pictureOf(scene.id)) problems.push(`${scene.id}'s record names ${String(entry.file)}, not ${pictureOf(scene.id)}`)
    const bytes = file(pictureOf(scene.id))
    if (bytes === undefined) {
      problems.push(`${pictureOf(scene.id)} does not exist, and its record says it was taken`)
      continue
    }
    if (bytes.length !== entry.bytes || digest(bytes) !== entry.sha256) {
      problems.push(
        `${pictureOf(scene.id)} is not the picture its record describes (${String(bytes.length)} bytes, recorded ${String(entry.bytes)}): it was changed by hand, or the record was`,
      )
    }
  }
  return problems
}

/** The pictures' directory holds nothing but the record and the scenes' pictures, and the record nothing but scenes. */
export function orphanProblems({ scenes, record, listing }) {
  const wanted = new Set(['captured.json', ...scenes.map((scene) => `${scene.id}.webp`)])
  return [
    ...listing.filter((name) => !wanted.has(name)).map((name) => `docs/images/readme/${name} is no scene's picture`),
    ...Object.keys(record)
      .filter((id) => !scenes.some((scene) => scene.id === id))
      .map((id) => `captured.json records ${id}, which is no scene of scenes.json`),
  ]
}

/** Every quote is listed and occurs in each part it names, and every recorded line decodes. */
export function quoteProblems({ scenes, record }) {
  const problems = []
  for (const scene of scenes) {
    const text = record[scene.id]?.text
    if (text !== undefined) problems.push(...undecodable(scene.id, text))
    // A scene without a record is held to its keys only; integrityProblems says it has no record.
    problems.push(...misquotes(scene, text))
  }
  return problems
}

/** Every record was taken on the same look. */
export function lookProblems({ record }) {
  const looks = [...new Set(Object.values(record).map((entry) => describeLook(entry.look)))]
  return looks.length <= 1
    ? []
    : [
        `the pictures were taken on ${String(looks.length)} looks, and every one must be taken on one: ${looks.join('; ')}; \`node scripts/pictures.mjs --all\` retakes every picture`,
      ]
}

/** Every relative link and picture source in `markdown`: a Markdown link's target, and an `src="…"`. */
function relativeTargets(markdown) {
  return [...markdown.matchAll(/\]\(([^)\s]+)\)|\bsrc="([^"]+)"/g)]
    .map((match) => match[1] ?? match[2])
    .filter((target) => !/^[a-z]+:/i.test(target) && !target.startsWith('#'))
}

/**
 * Every relative link and picture in README.md's generated regions names a
 * file that exists: a caption's, said by its scene, and what the render
 * writes itself -- every <img> -- said by its region. A render that cannot
 * be drawn is guardProblems' to say.
 */
export function linkProblems({ scenes, record, exists }) {
  const missing = (target) => !exists(target.split('#')[0].replace(/^\.\//, ''))
  const problems = []
  const inCaptions = new Set()
  for (const scene of scenes) {
    for (const target of relativeTargets(scene.caption ?? '')) {
      inCaptions.add(target)
      if (missing(target)) problems.push(`${scene.id}'s caption links ${target}, which is no file of the repository`)
    }
  }
  let rendered = {}
  try {
    rendered = render(scenes, record ?? {})
  } catch {
    // guardProblems says the regions could not be rendered.
  }
  for (const [name, text] of Object.entries(rendered)) {
    for (const target of new Set(relativeTargets(text))) {
      if (!inCaptions.has(target) && missing(target)) problems.push(`README.md's pictures region "${name}" links ${target}, which is no file of the repository`)
    }
  }
  return problems
}

/** The scenes' shape: ids, apps, placements, one hero, the texts, a width only as a whole number, and an app script for every app. */
export function shapeProblems({ scenes, appScripts }) {
  const problems = []
  const seen = new Set()
  for (const scene of scenes) {
    const id = String(scene.id)
    if (!/^[a-z0-9-]+$/.test(id)) problems.push(`the scene id ${JSON.stringify(scene.id)} is not [a-z0-9-]+`)
    if (seen.has(id)) problems.push(`the scene id ${id} is used twice`)
    seen.add(id)
    if (!PLACEMENTS.includes(scene.placement)) problems.push(`${id}: placement ${JSON.stringify(scene.placement)} is none of ${PLACEMENTS.join(', ')}`)
    for (const key of ['title', 'caption', 'alt']) if (typeof scene[key] !== 'string' || scene[key].trim() === '') problems.push(`${id} has no ${key}`)
    if (scene.placement === 'more' && typeof scene.title === 'string' && scene.title.includes(','))
      problems.push(`${id}'s title has a comma in it, and a <details> summary joins titles with commas, so it would read as two scenes`)
    if (typeof scene.alt === 'string' && /`|\*|\]\(|<|>|(^|\s)_|_(\s|$)/.test(scene.alt))
      problems.push(`${id}'s alt has Markdown in it, which an alt shows as written`)
    if (scene.width !== undefined && !(Number.isInteger(scene.width) && scene.width > 0))
      problems.push(`${id}: width ${JSON.stringify(scene.width)} is not a whole number of CSS pixels`)
    if (!appScripts.includes(scene.app))
      problems.push(`${id}: apps/${String(scene.app)}/scripts/pictures.mjs does not exist, so nothing takes or checks this picture`)
  }
  if (scenes.length === 0) problems.push('scenes.json has no scene, so the README shows no picture and nothing is checked')
  const heroes = scenes.filter((scene) => scene.placement === 'hero').length
  if (heroes !== 1) problems.push(`scenes.json must have exactly one hero scene, the picture README.md opens with; it has ${String(heroes)}`)
  return problems
}

/**
 * The guard on the guard: every app with a pictures script has a scene, and
 * every region drew a picture. `drawn` is the render, given only by a test
 * that shows a region without one refused.
 */
export function guardProblems({ scenes, record, appScripts }, drawn) {
  const problems = appScripts
    .filter((app) => !scenes.some((scene) => scene.app === app))
    .map((app) => `apps/${app}/scripts/pictures.mjs takes no scene of scenes.json, so its check would compare nothing`)
  let rendered = drawn
  try {
    rendered ??= render(scenes, record)
  } catch (error) {
    return [...problems, `the regions could not be rendered, so none drew a picture: ${error.message}`]
  }
  for (const [name, text] of Object.entries(rendered)) if (!text.includes('<img ')) problems.push(`the pictures region "${name}" renders no picture`)
  return problems
}

// `node scripts/pictures/readme.mjs --write` rewrites README.md's pictures regions.
if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = rewrite(readFileSync(README, 'utf8'), readScenes(), readRecord())
  if (process.argv.includes('--write')) {
    writeFileSync(README, next, 'utf8')
    console.log(`README.md: ${String(regionNames(readScenes()).length)} pictures region(s) written from scenes.json and captured.json`)
  } else {
    process.stdout.write(next)
  }
}
